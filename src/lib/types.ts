export interface User {
  id: number;
  username: string;
  role: 'admin' | 'user';
  tier: 'premium' | 'free';
  plan?: 'free' | 'monthly' | 'unlimited';
  premium_expires_at?: string | null;
  has_voxcpm_license?: boolean | number;
  voxcpm_license_expires_at?: string | null;
  created_at?: string;
  is_active?: number | boolean;
}

export interface SubscriptionPlan {
  id: string;
  label_km: string;
  label_en: string;
  price_usd: number;
  days: number;
  sort: number;
  visible: number;
  badge: '' | 'popular' | 'best';
  vox_label: string;
  /** VoxCPM2 minutes per plan term (free: lifetime trial). -1 = unlimited */
  vox_minutes: number;
  /** standard AI-voice minutes per term. -1 = unlimited */
  ai_minutes: number;
  /** 1 = may split a long video into ≤10-minute parts */
  long_video: number;
  /** distinct Pro voices per video. -1 = unlimited, 0 = none */
  pro_voices: number;
  own_vox_url: number;
  pitch_km: string;
  /** bullet lines generated by the server from the numbers above */
  features: string[];
  perMonth: number;
}

export interface MinuteBucket {
  /** minutes in the plan; -1 = unlimited */
  limit: number;
  usedMin: number;
  /** -1 = unlimited */
  remainingMin: number;
  remainingSec: number;
}

